/* Train the bundled on-device message-priority model.
 *
 *   npx tsx scripts/ai/train-priority-model.ts           # train, evaluate and write
 *   npx tsx scripts/ai/train-priority-model.ts --check   # fail if the bundle is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PriorityClassifier } from '../../src/features/ai/application/PriorityClassifier';
import { MODEL_CLASSES, trainPriorityModel, type LabeledMessage } from '../../src/features/ai/domain/training';
import type { MessagePriority } from '../../src/features/ai/domain/types';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const corpusPath = join(root, 'scripts', 'ai', 'priority-corpus.json');
const modelPath = join(root, 'src', 'features', 'ai', 'model', 'priorityModel.ts');
const FOLDS = 5;

export function loadCorpus(path = corpusPath): LabeledMessage[] {
  const corpus = JSON.parse(readFileSync(path, 'utf8')) as Record<string, unknown>;
  return MODEL_CLASSES.flatMap(priority => {
    const texts = corpus[priority];
    if (!Array.isArray(texts) || texts.some(text => typeof text !== 'string' || text.trim() === '')) {
      throw new TypeError(`Corpus class ${priority} must be a list of non-empty strings`);
    }
    return (texts as string[]).map(text => ({ text, priority }));
  });
}

export function renderModel(examples: readonly LabeledMessage[]): string {
  const model = trainPriorityModel(examples);
  const entries = Object.entries(model.features).map(([feature, weights]) => `    ${JSON.stringify(feature)}: [${weights.join(', ')}],`);
  return [
    '// Generated by scripts/ai/train-priority-model.ts from scripts/ai/priority-corpus.json.',
    '// Do not edit by hand: change the corpus or features, then retrain.',
    "import type { PriorityModel } from '../domain/types';",
    '',
    'export const PRIORITY_MODEL: PriorityModel = {',
    '  version: 1,',
    `  classes: ${JSON.stringify(model.classes).replace(/"/g, "'").replace(/,/g, ', ')},`,
    `  priors: [${model.priors.join(', ')}],`,
    '  features: {',
    ...entries,
    '  },',
    '};',
    '',
  ].join('\n');
}

/** Stratified k-fold: every class contributes to each held-out fold. */
function crossValidate(examples: readonly LabeledMessage[]): void {
  const confusion = new Map<string, number>();
  let correct = 0;
  const position = new Map<MessagePriority, number>();
  const fold = examples.map(example => {
    const index = position.get(example.priority) ?? 0;
    position.set(example.priority, index + 1);
    return index % FOLDS;
  });
  for (let held = 0; held < FOLDS; held += 1) {
    const classifier = new PriorityClassifier(trainPriorityModel(examples.filter((_example, index) => fold[index] !== held)));
    examples.forEach((example, index) => {
      if (fold[index] !== held) return;
      const predicted = classifier.classify(example.text).priority;
      if (predicted === example.priority) correct += 1;
      const key = `${example.priority}>${predicted}`;
      confusion.set(key, (confusion.get(key) ?? 0) + 1);
    });
  }
  console.log(`${FOLDS}-fold accuracy: ${(100 * correct / examples.length).toFixed(1)}% of ${examples.length} messages`);
  console.log(`actual \\ predicted  ${MODEL_CLASSES.map(name => name.padStart(8)).join('')}`);
  for (const actual of MODEL_CLASSES) {
    const row = MODEL_CLASSES.map(predicted => String(confusion.get(`${actual}>${predicted}`) ?? 0).padStart(8)).join('');
    const total = examples.filter(example => example.priority === actual).length;
    const recall = (100 * (confusion.get(`${actual}>${actual}`) ?? 0) / total).toFixed(0);
    console.log(`${actual.padEnd(19)}${row}   recall ${recall}%`);
  }
}

function main(): void {
  const examples = loadCorpus();
  const rendered = renderModel(examples);
  if (process.argv.includes('--check')) {
    if (readFileSync(modelPath, 'utf8') !== rendered) {
      console.error('Bundled priority model is stale. Run: npx tsx scripts/ai/train-priority-model.ts');
      process.exit(1);
    }
    console.log('Bundled priority model matches the corpus.');
    return;
  }
  crossValidate(examples);
  writeFileSync(modelPath, rendered);
  console.log(`Wrote ${Object.keys(trainPriorityModel(examples).features).length} features to ${modelPath}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
