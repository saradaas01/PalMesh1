#!/usr/bin/env python3
"""Validate and atomically stage identical offline resources for both platforms."""
from __future__ import annotations
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import sqlite3
import sys
import tempfile
from mbtiles import checked_manifest, sha256

ROOT = Path(__file__).resolve().parents[2]
MAP_LICENSE_SHA256 = '77d2692c3d64efdd4db18dce2407699baf62930e2b50d6e5ed90b48acf16b7c1'


def stage(source: Path, destination: Path, expected_sha256: str | None = None) -> None:
    expected = sha256(source) if expected_sha256 is None else expected_sha256
    destination.parent.mkdir(parents=True, exist_ok=True)
    descriptor, name = tempfile.mkstemp(prefix='.' + destination.name + '.', suffix='.copying', dir=destination.parent)
    temporary = Path(name)
    try:
        with os.fdopen(descriptor, 'wb') as copied, source.open('rb') as original:
            shutil.copyfileobj(original, copied, length=1024 * 1024)
            copied.flush()
            os.fsync(copied.fileno())
        if sha256(temporary) != expected:
            raise ValueError('Copy checksum mismatch; the source may have changed after validation')
        temporary.replace(destination)
    finally:
        temporary.unlink(missing_ok=True)


def checked_fonts(font_root: Path) -> dict:
    fonts = json.loads((font_root / 'manifest.json').read_text(encoding='utf-8'))
    expected_paths = {'Klokantech Noto Sans Regular/%d-%d.pbf' % (low, low + 255) for low in range(0, 65536, 256)}
    if not isinstance(fonts, dict) or fonts.get('fontstack') != 'Klokantech Noto Sans Regular' or fonts.get('rangeCount') != 256 or not isinstance(fonts.get('ranges'), dict) or set(fonts['ranges']) != expected_paths:
        raise ValueError('The complete BMP glyph atlas with its exact native font name is required')
    for relative, expected in fonts['ranges'].items():
        path = font_root / relative
        if not isinstance(expected, str) or not re.fullmatch(r'[a-f0-9]{64}', expected) or path.is_symlink() or not path.is_file() or not 0 < path.stat().st_size <= 512 * 1024 or sha256(path) != expected:
            raise ValueError('Font checksum or native glyph size limit mismatch: ' + relative)
    license_file = font_root / 'LICENSE-OFL.txt'
    if license_file.is_symlink() or not license_file.is_file() or license_file.stat().st_size > 65536 or 'SIL OPEN FONT LICENSE Version 1.1' not in license_file.read_text(encoding='utf-8'):
        raise ValueError('The bundled glyph SIL Open Font License is required')
    return fonts


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--map', type=Path, default=ROOT / 'mapdata/palestine.mbtiles')
    parser.add_argument('--manifest', type=Path, default=ROOT / 'mapdata/palestine.manifest.json')
    parser.add_argument('--fonts-only', action='store_true', help='Stage glyphs without claiming that a map exists')
    parser.add_argument('--check', action='store_true', help='Check source resources without staging')
    args = parser.parse_args()
    font_root = ROOT / 'assets/map-fonts'
    fonts = checked_fonts(font_root)
    manifest_digest = None if args.fonts_only else sha256(args.manifest)
    manifest = None if args.fonts_only else checked_manifest(args.manifest, args.map)
    license_root = ROOT / 'assets/map-licenses'
    if manifest is not None and (sha256(license_root / 'LICENSE-ODbL-1.0.txt') != MAP_LICENSE_SHA256 or not (license_root / 'OSM-ATTRIBUTION.txt').is_file()):
        raise ValueError('The offline ODbL license and OSM attribution notice are required')
    destinations = [ROOT / 'android/app/src/main/assets/palmesh', ROOT / 'ios/PalMesh/palmesh']
    if not args.check:
        for destination in destinations:
            for relative in fonts['ranges']:
                stage(font_root / relative, destination / 'fonts' / relative, fonts['ranges'][relative])
            stage(font_root / 'LICENSE-OFL.txt', destination / 'fonts/LICENSE-OFL.txt')
            stage(font_root / 'manifest.json', destination / 'fonts/manifest.json')
            if manifest is not None:
                stage(args.map, destination / 'palestine.mbtiles', manifest['sha256'])
                stage(args.manifest, destination / 'palestine.manifest.json', manifest_digest)
                stage(license_root / 'LICENSE-ODbL-1.0.txt', destination / 'licenses/LICENSE-ODbL-1.0.txt', MAP_LICENSE_SHA256)
                stage(license_root / 'OSM-ATTRIBUTION.txt', destination / 'licenses/OSM-ATTRIBUTION.txt')
        if manifest is not None:
            # Native factory can import this file without reading SQLite or guessing a digest.
            output = ROOT / 'src/features/maps/infrastructure/bundledMap.ts'
            text = '/** Generated by scripts/maps/package.py after artifact validation. */\n' + \
                'export const bundledMapOptions = Object.freeze({ assetName: \'palmesh/palestine.mbtiles\', expectedSha256: \'%s\' });\n' % manifest['sha256']
            output.write_text(text, encoding='utf-8')
    print('Verified 256 bundled glyph pages.' + (' Palestine map verified' + ('.' if args.check else ' and staged.') if manifest is not None else ' No map was packaged.'))


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError, KeyError, sqlite3.Error) as error:
        print('Offline map packaging failed: ' + str(error), file=sys.stderr)
        sys.exit(1)
