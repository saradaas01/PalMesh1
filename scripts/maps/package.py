#!/usr/bin/env python3
"""Validate and atomically stage identical offline resources for both platforms."""
from __future__ import annotations
import argparse
import json
import os
from pathlib import Path
import shutil
import sys
from mbtiles import checked_manifest, sha256

ROOT = Path(__file__).resolve().parents[2]


def stage(source: Path, destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_name(destination.name + '.copying')
    try:
        shutil.copyfile(source, temporary)
        with temporary.open('rb') as copied:
            os.fsync(copied.fileno())
        if sha256(source) != sha256(temporary):
            raise ValueError('Copy checksum mismatch')
        temporary.replace(destination)
    finally:
        temporary.unlink(missing_ok=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--map', type=Path, default=ROOT / 'mapdata/palestine.mbtiles')
    parser.add_argument('--manifest', type=Path, default=ROOT / 'mapdata/palestine.manifest.json')
    parser.add_argument('--fonts-only', action='store_true', help='Stage glyphs without claiming that a map exists')
    parser.add_argument('--check', action='store_true', help='Check source resources without staging')
    args = parser.parse_args()
    font_root = ROOT / 'assets/map-fonts'
    fonts = json.loads((font_root / 'manifest.json').read_text())
    if fonts['rangeCount'] != 256 or len(fonts['ranges']) != 256:
        raise ValueError('The complete BMP glyph atlas is required')
    for relative, expected in fonts['ranges'].items():
        if sha256(font_root / relative) != expected:
            raise ValueError('Font checksum mismatch: ' + relative)
    manifest = None if args.fonts_only else checked_manifest(args.manifest, args.map)
    destinations = [ROOT / 'android/app/src/main/assets/palmesh', ROOT / 'ios/PalMesh/palmesh']
    if not args.check:
        for destination in destinations:
            for relative in fonts['ranges']:
                stage(font_root / relative, destination / 'fonts' / relative)
            stage(font_root / 'LICENSE-OFL.txt', destination / 'fonts/LICENSE-OFL.txt')
            stage(font_root / 'manifest.json', destination / 'fonts/manifest.json')
            if manifest is not None:
                stage(args.map, destination / 'palestine.mbtiles')
                stage(args.manifest, destination / 'palestine.manifest.json')
        if manifest is not None:
            # Native factory can import this file without reading SQLite or guessing a digest.
            output = ROOT / 'src/features/maps/infrastructure/bundledMap.ts'
            text = '/** Generated by scripts/maps/package.py after artifact validation. */\n' + \
                'export const bundledMapOptions = Object.freeze({ assetName: \'palmesh/palestine.mbtiles\', expectedSha256: \'%s\' });\n' % manifest['sha256']
            output.write_text(text, encoding='utf-8')
    print('Verified 256 bundled glyph pages.' + (' Palestine map verified and staged.' if manifest is not None else ' No map was packaged.'))


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError, KeyError) as error:
        print('Offline map packaging failed: ' + str(error), file=sys.stderr)
        sys.exit(1)
